import * as vscode from 'vscode';
import * as path from 'path';

// ─────────────────────────────────────────────────────────────────────────────
//  TYPES & INTERFACES
// ─────────────────────────────────────────────────────────────────────────────

export type LineOrigin = 'manual' | 'pasted' | 'ai' | 'mixed';

export interface LineProvenanceRecordState {
  origin: LineOrigin;
  timestamp: number;
  charCount?: number;
  preview?: string;
}

export interface PastedRangeSummary {
  /** 1-indexed start line for display & telemetry reporting */
  startLine: number;
  /** 1-indexed end line for display & telemetry reporting */
  endLine: number;
  /** Total characters in the pasted range */
  charCount: number;
  /** Snippet preview */
  preview?: string;
}

export interface DocumentProvenanceSummary {
  uri: string;
  fileName: string;
  totalLines: number;
  manualLineCount: number;
  aiLineCount: number;
  pastedLineCount: number;
  mixedLineCount: number;
  manualPercentage: number;
  aiPercentage: number;
  pastedPercentage: number;
  pastedRanges: PastedRangeSummary[];
  isHighlightingEnabled: boolean;
  activeLine?: number;
}

// ─────────────────────────────────────────────────────────────────────────────
//  AI SIGNATURE CHECKER
// ─────────────────────────────────────────────────────────────────────────────

export function hasAiContentSignatures(text: string): boolean {
  return (
    /\/\/\s*(here('?s| is)|generated (by|with)|auto-?generated|ai[- ]assistant|copilot|chatgpt|claude|gemini|openai|step \d+:|helper function to|implementation of|prompt:|solution:)/i.test(text) ||
    /\/\*\s*(auto-?generated|generated by ai|ai assistant|solution provided by|copilot)/i.test(text) ||
    /```(?:js|javascript|ts|typescript|python|py|html|css|json)?/i.test(text) ||
    /^(?:Certainly!|Sure!|Here is|Below is the code|This function|I have created|Hope this helps)/im.test(text)
  );
}

// ─────────────────────────────────────────────────────────────────────────────
//  LINE PROVENANCE TRACKER CLASS
// ─────────────────────────────────────────────────────────────────────────────

export class LineProvenanceTracker implements vscode.Disposable {
  private _isHighlightingEnabled: boolean = true;
  private _documentStates: Map<string, Map<number, LineProvenanceRecordState>> = new Map();
  private _debounceTimers: Map<string, NodeJS.Timeout> = new Map();
  private _disposables: vscode.Disposable[] = [];

  // Visual Editor Decoration Types
  public pastedLineDecoration: vscode.TextEditorDecorationType;
  public aiLineDecoration: vscode.TextEditorDecorationType;
  public manualLineDecoration: vscode.TextEditorDecorationType;
  public mixedLineDecoration: vscode.TextEditorDecorationType;

  // Event hook for telemetry & dashboard broadcast
  private _onProvenanceChanged = new vscode.EventEmitter<DocumentProvenanceSummary>();
  public readonly onProvenanceChanged: vscode.Event<DocumentProvenanceSummary> = this._onProvenanceChanged.event;

  constructor() {
    // 1. PASTED Line Decoration (soft red background with badge [PASTED])
    this.pastedLineDecoration = vscode.window.createTextEditorDecorationType({
      backgroundColor: 'rgba(239, 68, 68, 0.14)',
      isWholeLine: true,
      overviewRulerColor: 'rgba(239, 68, 68, 0.85)',
      overviewRulerLane: vscode.OverviewRulerLane.Right
    });

    // 2. AI GENERATED Line Decoration (soft purple background with badge [AI])
    this.aiLineDecoration = vscode.window.createTextEditorDecorationType({
      backgroundColor: 'rgba(168, 85, 247, 0.13)',
      isWholeLine: true,
      overviewRulerColor: 'rgba(168, 85, 247, 0.85)',
      overviewRulerLane: vscode.OverviewRulerLane.Right
    });

    // 3. MANUALLY TYPED Line Decoration (clean subtle soft green background with badge [MANUAL])
    this.manualLineDecoration = vscode.window.createTextEditorDecorationType({
      backgroundColor: 'rgba(34, 197, 94, 0.08)',
      isWholeLine: true,
      overviewRulerColor: 'rgba(34, 197, 94, 0.50)',
      overviewRulerLane: vscode.OverviewRulerLane.Left
    });

    // 4. MIXED Line Decoration (soft amber background with badge [MIXED])
    this.mixedLineDecoration = vscode.window.createTextEditorDecorationType({
      backgroundColor: 'rgba(245, 158, 11, 0.12)',
      isWholeLine: true,
      overviewRulerColor: 'rgba(245, 158, 11, 0.70)',
      overviewRulerLane: vscode.OverviewRulerLane.Right
    });
  }

  /**
   * Register event handlers for document changes, editor switches, and document close.
   */
  public register(context: vscode.ExtensionContext): void {
    // Listen to text document edits
    this._disposables.push(
      vscode.workspace.onDidChangeTextDocument(event => this.handleDocumentChange(event))
    );

    // Listen to active editor switches to re-render decorations instantly
    this._disposables.push(
      vscode.window.onDidChangeActiveTextEditor(editor => {
        if (editor && editor.document.uri.scheme === 'file') {
          this.applyDecorations(editor);
          this.emitSummary(editor.document);
        }
      })
    );

    // Clean up state when documents are closed to avoid memory leaks
    this._disposables.push(
      vscode.workspace.onDidCloseTextDocument(doc => {
        const uriStr = doc.uri.toString();
        this._documentStates.delete(uriStr);
        const timer = this._debounceTimers.get(uriStr);
        if (timer) {
          clearTimeout(timer);
          this._debounceTimers.delete(uriStr);
        }
      })
    );

    // Initial render for active editor if already open
    if (vscode.window.activeTextEditor && vscode.window.activeTextEditor.document.uri.scheme === 'file') {
      this.applyDecorations(vscode.window.activeTextEditor);
    }
  }

  /**
   * Main Text Document Event Monitoring handler.
   * Accurately categorizes edits:
   * - Enter key / manual keypresses -> [MANUAL]
   * - AI signatures / code blocks -> [AI]
   * - Multi-line paste from clipboard -> [PASTED]
   * - Typing on existing pasted/AI line -> [MIXED]
   */
  public handleDocumentChange(event: vscode.TextDocumentChangeEvent): void {
    const document = event.document;
    if (document.uri.scheme !== 'file') return;
    if (event.contentChanges.length === 0) return;

    const uriStr = document.uri.toString();
    let docMap = this._documentStates.get(uriStr);
    if (!docMap) {
      docMap = new Map<number, LineProvenanceRecordState>();
      this._documentStates.set(uriStr, docMap);
    }

    // Defensive handling: Process multi-cursor changes from bottom to top
    // so line index shifts for upper lines do not distort lower line calculations
    const sortedChanges = [...event.contentChanges].sort((a, b) => {
      if (b.range.start.line !== a.range.start.line) {
        return b.range.start.line - a.range.start.line;
      }
      return b.range.start.character - a.range.start.character;
    });

    const now = Date.now();

    for (const change of sortedChanges) {
      const text = change.text;
      const textLen = text.length;
      const startLine = change.range.start.line;
      const endLine = change.range.end.line;
      const deletedLineCount = endLine - startLine;
      const insertedLines = text.split(/\r?\n/);
      const addedLineCount = insertedLines.length - 1;

      // ── Categorize Insertion ───────────────────────────────────────────────
      const isSingleKey = textLen === 1;
      const isEnterKey = text === '\n' || text === '\r\n';
      const isTabOrIndent = /^\s{1,8}$/.test(text);
      const isAutoClosePair = /^(\(\)|\[\]|\{\}|""|''|``|<>)$/.test(text);
      const hasAi = hasAiContentSignatures(text);

      const nonEmptyInserted = insertedLines.filter(l => l.trim().length > 0);
      const isMultiLinePaste = !isEnterKey && nonEmptyInserted.length > 1;

      let insertionOrigin: LineOrigin = 'manual';
      if (hasAi) {
        insertionOrigin = 'ai';
      } else if (isMultiLinePaste || (!isEnterKey && !isSingleKey && !isTabOrIndent && !isAutoClosePair)) {
        insertionOrigin = 'pasted';
      } else if (isEnterKey || isSingleKey || isAutoClosePair) {
        insertionOrigin = 'manual';
      }

      // ── Step 1: Handle Line Deletions & Line Number Shifting ───────────────
      if (deletedLineCount > 0) {
        for (let l = startLine + 1; l <= endLine; l++) {
          docMap.delete(l);
        }

        const shiftedMap = new Map<number, LineProvenanceRecordState>();
        for (const [lineIdx, state] of docMap.entries()) {
          if (lineIdx <= startLine) {
            shiftedMap.set(lineIdx, state);
          } else if (lineIdx > endLine) {
            shiftedMap.set(lineIdx - deletedLineCount, state);
          }
        }
        docMap = shiftedMap;
        this._documentStates.set(uriStr, docMap);
      }

      // ── Step 2: Handle Line Additions & Line Number Shifting ───────────────
      if (addedLineCount > 0) {
        const shiftedMap = new Map<number, LineProvenanceRecordState>();
        for (const [lineIdx, state] of docMap.entries()) {
          if (lineIdx <= startLine) {
            shiftedMap.set(lineIdx, state);
          } else {
            shiftedMap.set(lineIdx + addedLineCount, state);
          }
        }
        docMap = shiftedMap;
        this._documentStates.set(uriStr, docMap);
      }

      // ── Step 3: Record Provenance on Inserted / Modified Lines ─────────────
      if (textLen > 0) {
        if (isEnterKey) {
          // Pressing Enter: startLine retains its existing typing/paste/ai origin.
          // The newly created line (startLine + 1) is created by manual keypress [MANUAL].
          if (!docMap.has(startLine)) {
            docMap.set(startLine, {
              origin: 'manual',
              timestamp: now,
              charCount: 0
            });
          }
          docMap.set(startLine + 1, {
            origin: 'manual',
            timestamp: now,
            charCount: 0
          });
        } else {
          for (let offset = 0; offset <= addedLineCount; offset++) {
            const targetLine = startLine + offset;
            const lineSlice = insertedLines[offset] || '';

            if (offset === 0 && lineSlice === '' && addedLineCount > 0 && docMap.has(targetLine)) {
              continue;
            }

            if (insertionOrigin === 'ai') {
              docMap.set(targetLine, {
                origin: 'ai',
                timestamp: now,
                charCount: lineSlice.length,
                preview: lineSlice.slice(0, 80)
              });
            } else if (insertionOrigin === 'pasted') {
              docMap.set(targetLine, {
                origin: 'pasted',
                timestamp: now,
                charCount: lineSlice.length,
                preview: lineSlice.slice(0, 80)
              });
            } else {
              // Manual typing on targetLine
              const existing = docMap.get(targetLine);
              if (existing && (existing.origin === 'pasted' || existing.origin === 'ai')) {
                // User typed manually on a line that was previously pasted or AI
                docMap.set(targetLine, {
                  origin: 'mixed',
                  timestamp: now,
                  charCount: (existing.charCount || 0) + textLen,
                  preview: lineSlice.slice(0, 80)
                });
              } else {
                docMap.set(targetLine, {
                  origin: 'manual',
                  timestamp: now,
                  charCount: (existing?.charCount || 0) + textLen,
                  preview: lineSlice.slice(0, 80)
                });
              }
            }
          }
        }
      }
    }

    // ── Step 4: Defensive Pruning for Undo/Redo & Document Boundaries ───────
    const maxLine = document.lineCount;
    for (const lineIdx of Array.from(docMap.keys())) {
      if (lineIdx >= maxLine) {
        docMap.delete(lineIdx);
      }
    }

    // Schedule debounced visual rendering (100ms) to ensure zero editor input lag
    const editor = vscode.window.visibleTextEditors.find(e => e.document.uri.toString() === uriStr);
    if (editor) {
      this.scheduleDecorations(editor, 100);
    }

    this.emitSummary(document);
  }

  /**
   * Schedule visual decoration rendering with a 100ms debounce.
   */
  private scheduleDecorations(editor: vscode.TextEditor, delayMs: number = 100): void {
    const uriStr = editor.document.uri.toString();
    const existingTimer = this._debounceTimers.get(uriStr);
    if (existingTimer) {
      clearTimeout(existingTimer);
    }

    const timer = setTimeout(() => {
      this._debounceTimers.delete(uriStr);
      this.applyDecorations(editor);
    }, delayMs);

    this._debounceTimers.set(uriStr, timer);
  }

  /**
   * Apply visual in-editor decorations using VS Code TextEditorDecorationType.
   * Renders badges [MANUAL], [AI], [PASTED], and [MIXED].
   */
  public applyDecorations(editor: vscode.TextEditor): void {
    if (!this._isHighlightingEnabled) {
      // Clear decorations if highlighting is toggled off
      editor.setDecorations(this.pastedLineDecoration, []);
      editor.setDecorations(this.aiLineDecoration, []);
      editor.setDecorations(this.manualLineDecoration, []);
      editor.setDecorations(this.mixedLineDecoration, []);
      return;
    }

    const document = editor.document;
    const uriStr = document.uri.toString();
    const docMap = this._documentStates.get(uriStr);
    if (!docMap || docMap.size === 0) {
      editor.setDecorations(this.pastedLineDecoration, []);
      editor.setDecorations(this.aiLineDecoration, []);
      editor.setDecorations(this.manualLineDecoration, []);
      editor.setDecorations(this.mixedLineDecoration, []);
      return;
    }

    const pastedOptions: vscode.DecorationOptions[] = [];
    const aiOptions: vscode.DecorationOptions[] = [];
    const manualOptions: vscode.DecorationOptions[] = [];
    const mixedOptions: vscode.DecorationOptions[] = [];

    const totalLines = document.lineCount;

    for (let line = 0; line < totalLines; line++) {
      const state = docMap.get(line);
      if (!state) continue;

      const lineText = document.lineAt(line).text;
      const lineRange = document.lineAt(line).range;
      const hasContent = lineText.trim().length > 0;
      const formattedTime = new Date(state.timestamp).toLocaleTimeString();

      if (state.origin === 'ai') {
        const hover = new vscode.MarkdownString();
        hover.isTrusted = true;
        hover.appendMarkdown(`### 🤖 AI Generated Code\n`);
        hover.appendMarkdown(`- **Status**: \`[AI]\`\n`);
        hover.appendMarkdown(`- **Origin**: AI Assistant / Generated code block\n`);
        hover.appendMarkdown(`- **Line**: ${line + 1}\n`);
        hover.appendMarkdown(`- **Captured**: ${formattedTime}\n`);

        aiOptions.push({
          range: lineRange,
          hoverMessage: hover,
          renderOptions: hasContent ? {
            after: {
              contentText: '  [AI]',
              color: 'rgba(168, 85, 247, 0.95)',
              fontStyle: 'italic',
              fontWeight: '600'
            }
          } : undefined
        });
      } else if (state.origin === 'pasted') {
        const hover = new vscode.MarkdownString();
        hover.isTrusted = true;
        hover.appendMarkdown(`### 📋 Pasted Code\n`);
        hover.appendMarkdown(`- **Status**: \`[PASTED]\`\n`);
        hover.appendMarkdown(`- **Origin**: Clipboard paste / External snippet\n`);
        hover.appendMarkdown(`- **Line**: ${line + 1}\n`);
        hover.appendMarkdown(`- **Captured**: ${formattedTime}\n`);

        pastedOptions.push({
          range: lineRange,
          hoverMessage: hover,
          renderOptions: hasContent ? {
            after: {
              contentText: '  [PASTED]',
              color: 'rgba(239, 68, 68, 0.90)',
              fontStyle: 'italic',
              fontWeight: '600'
            }
          } : undefined
        });
      } else if (state.origin === 'mixed') {
        const hover = new vscode.MarkdownString();
        hover.isTrusted = true;
        hover.appendMarkdown(`### 🔶 Mixed Origin Code\n`);
        hover.appendMarkdown(`- **Status**: \`[MIXED]\`\n`);
        hover.appendMarkdown(`- **Origin**: Pasted / AI code modified by manual typing\n`);
        hover.appendMarkdown(`- **Line**: ${line + 1}\n`);
        hover.appendMarkdown(`- **Last Edit**: ${formattedTime}\n`);

        mixedOptions.push({
          range: lineRange,
          hoverMessage: hover,
          renderOptions: hasContent ? {
            after: {
              contentText: '  [MIXED]',
              color: 'rgba(245, 158, 11, 0.85)',
              fontStyle: 'italic',
              fontWeight: '600'
            }
          } : undefined
        });
      } else if (state.origin === 'manual') {
        const hover = new vscode.MarkdownString();
        hover.isTrusted = true;
        hover.appendMarkdown(`### ✍️ Organic Manual Code\n`);
        hover.appendMarkdown(`- **Status**: \`[MANUAL]\`\n`);
        hover.appendMarkdown(`- **Origin**: Manually typed keystrokes\n`);
        hover.appendMarkdown(`- **Line**: ${line + 1}\n`);
        hover.appendMarkdown(`- **Timestamp**: ${formattedTime}\n`);

        manualOptions.push({
          range: lineRange,
          hoverMessage: hover,
          renderOptions: hasContent ? {
            after: {
              contentText: '  [MANUAL]',
              color: 'rgba(34, 197, 94, 0.85)',
              fontStyle: 'italic',
              fontWeight: '600'
            }
          } : undefined
        });
      }
    }

    editor.setDecorations(this.pastedLineDecoration, pastedOptions);
    editor.setDecorations(this.aiLineDecoration, aiOptions);
    editor.setDecorations(this.manualLineDecoration, manualOptions);
    editor.setDecorations(this.mixedLineDecoration, mixedOptions);
  }

  /**
   * Toggle visual in-editor highlighting on/off.
   */
  public toggleHighlighting(): boolean {
    this._isHighlightingEnabled = !this._isHighlightingEnabled;

    for (const editor of vscode.window.visibleTextEditors) {
      if (editor.document.uri.scheme === 'file') {
        this.applyDecorations(editor);
        this.emitSummary(editor.document);
      }
    }

    const statusStr = this._isHighlightingEnabled ? 'ENABLED' : 'DISABLED';
    vscode.window.showInformationMessage(`INCODE Line Provenance Highlighting is now ${statusStr}.`);
    return this._isHighlightingEnabled;
  }

  public get isHighlightingEnabled(): boolean {
    return this._isHighlightingEnabled;
  }

  /**
   * Telemetry Output: Returns summary for a document whenever an edit occurs.
   */
  public getDocumentSummary(document: vscode.TextDocument): DocumentProvenanceSummary {
    const uriStr = document.uri.toString();
    const docMap = this._documentStates.get(uriStr) || new Map<number, LineProvenanceRecordState>();
    const totalLines = Math.max(1, document.lineCount);

    let manualCount = 0;
    let aiCount = 0;
    let pastedCount = 0;
    let mixedCount = 0;

    for (let l = 0; l < document.lineCount; l++) {
      const st = docMap.get(l);
      if (st?.origin === 'ai') {
        aiCount++;
      } else if (st?.origin === 'pasted') {
        pastedCount++;
      } else if (st?.origin === 'mixed') {
        mixedCount++;
      } else if (st?.origin === 'manual') {
        manualCount++;
      }
    }

    const pastedRanges = this.computePastedRanges(document, docMap);
    const manualPercentage = totalLines > 0 ? Math.round((manualCount / totalLines) * 100) : 100;
    const aiPercentage = totalLines > 0 ? Math.round((aiCount / totalLines) * 100) : 0;
    const pastedPercentage = totalLines > 0 ? Math.round(((pastedCount + mixedCount) / totalLines) * 100) : 0;

    const activeEditor = vscode.window.activeTextEditor;
    const activeLine = activeEditor && activeEditor.document.uri.toString() === uriStr
      ? activeEditor.selection.active.line + 1
      : undefined;

    return {
      uri: uriStr,
      fileName: path.basename(document.uri.fsPath),
      totalLines: document.lineCount,
      manualLineCount: manualCount,
      aiLineCount: aiCount,
      pastedLineCount: pastedCount,
      mixedLineCount: mixedCount,
      manualPercentage,
      aiPercentage,
      pastedPercentage,
      pastedRanges,
      isHighlightingEnabled: this._isHighlightingEnabled,
      activeLine
    };
  }

  /**
   * Returns summary for current active editor document.
   */
  public getActiveSummary(): DocumentProvenanceSummary | null {
    const activeEditor = vscode.window.activeTextEditor;
    if (!activeEditor || activeEditor.document.uri.scheme !== 'file') {
      return null;
    }
    return this.getDocumentSummary(activeEditor.document);
  }

  /**
   * Aggregates contiguous pasted lines into ranges:
   * [{ startLine: 12, endLine: 45, charCount: 350 }]
   */
  public computePastedRanges(
    document: vscode.TextDocument,
    docMap: Map<number, LineProvenanceRecordState>
  ): PastedRangeSummary[] {
    const ranges: PastedRangeSummary[] = [];
    let rangeStart: number | null = null;
    let accumulatedChars = 0;
    let firstLinePreview = '';

    const totalLines = document.lineCount;

    for (let line = 0; line < totalLines; line++) {
      const state = docMap.get(line);
      const isPasted = state && (state.origin === 'pasted' || state.origin === 'mixed');

      if (isPasted) {
        if (rangeStart === null) {
          rangeStart = line + 1; // 1-indexed for presentation
          accumulatedChars = 0;
          firstLinePreview = document.lineAt(line).text.trim().slice(0, 50);
        }
        accumulatedChars += document.lineAt(line).text.length;
      } else {
        if (rangeStart !== null) {
          ranges.push({
            startLine: rangeStart,
            endLine: line, // 1-indexed inclusive end
            charCount: accumulatedChars,
            preview: firstLinePreview
          });
          rangeStart = null;
          accumulatedChars = 0;
        }
      }
    }

    if (rangeStart !== null) {
      ranges.push({
        startLine: rangeStart,
        endLine: totalLines,
        charCount: accumulatedChars,
        preview: firstLinePreview
      });
    }

    return ranges;
  }

  /**
   * Explicitly marks a range of lines as manual, ai_assisted, copy_paste, or mixed.
   */
  public markRange(
    document: vscode.TextDocument,
    startLine: number,
    endLine: number,
    provenance: 'copy_paste' | 'ai_assisted' | 'manual' | 'mixed'
  ): void {
    const uriStr = document.uri.toString();
    let docMap = this._documentStates.get(uriStr);
    if (!docMap) {
      docMap = new Map<number, LineProvenanceRecordState>();
      this._documentStates.set(uriStr, docMap);
    }
    const now = Date.now();
    for (let l = startLine; l <= endLine && l < document.lineCount; l++) {
      const lineText = document.lineAt(l).text;
      const origin: LineOrigin =
        provenance === 'ai_assisted' ? 'ai' :
        provenance === 'manual' ? 'manual' :
        provenance === 'mixed' ? 'mixed' : 'pasted';

      docMap.set(l, {
        origin,
        timestamp: now,
        charCount: lineText.length,
        preview: lineText.slice(0, 80)
      });
    }

    const editor = vscode.window.visibleTextEditors.find(e => e.document.uri.toString() === uriStr);
    if (editor) {
      this.scheduleDecorations(editor, 50);
    }
    this.emitSummary(document);
  }

  /**
   * Get direct line record array for syncing with FileActivityItem.
   */
  public getLineRecordsForFile(document: vscode.TextDocument): {
    lineNumber: number;
    lineText: string;
    provenance: 'manual' | 'ai_assisted' | 'copy_paste';
    isOffline: boolean;
    timestamp: string;
  }[] {
    const uriStr = document.uri.toString();
    const docMap = this._documentStates.get(uriStr);
    if (!docMap) return [];

    const result: {
      lineNumber: number;
      lineText: string;
      provenance: 'manual' | 'ai_assisted' | 'copy_paste';
      isOffline: boolean;
      timestamp: string;
    }[] = [];

    const totalLines = document.lineCount;
    for (let l = 0; l < totalLines; l++) {
      const s = docMap.get(l);
      if (!s) continue;
      const cleanText = document.lineAt(l).text.replace(/\r$/, '');
      const prov: 'manual' | 'ai_assisted' | 'copy_paste' =
        s.origin === 'manual' ? 'manual' :
        s.origin === 'ai' ? 'ai_assisted' :
        s.origin === 'mixed' ? 'copy_paste' :
        hasAiContentSignatures(cleanText) ? 'ai_assisted' : 'copy_paste';

      result.push({
        lineNumber: l + 1,
        lineText: cleanText.slice(0, 120),
        provenance: prov,
        isOffline: false,
        timestamp: new Date(s.timestamp).toISOString()
      });
    }

    return result;
  }

  private emitSummary(document: vscode.TextDocument): void {
    const summary = this.getDocumentSummary(document);
    this._onProvenanceChanged.fire(summary);
  }

  public dispose(): void {
    for (const timer of this._debounceTimers.values()) {
      clearTimeout(timer);
    }
    this._debounceTimers.clear();
    this._documentStates.clear();

    this.pastedLineDecoration.dispose();
    this.aiLineDecoration.dispose();
    this.manualLineDecoration.dispose();
    this.mixedLineDecoration.dispose();
    this._onProvenanceChanged.dispose();

    for (const d of this._disposables) {
      d.dispose();
    }
    this._disposables = [];
  }
}

// Global Singleton Instance
export const defaultLineProvenanceTracker = new LineProvenanceTracker();
