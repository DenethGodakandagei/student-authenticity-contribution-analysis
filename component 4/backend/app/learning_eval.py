"""Stage 9: pre/post tests and learning-gain scoring.

Questions are generated by the LLM as validated JSON. All scoring and metrics
are computed here in plain Python, never by the model.
"""
import json
import os
from datetime import datetime
from typing import Any, Dict, List, Optional

# pyrefly: ignore [missing-import]
from fastapi import APIRouter, Depends, HTTPException
# pyrefly: ignore [missing-import]
from pydantic import BaseModel, Field

from app.auth import get_current_user
from app.llm import BaseLLMProvider, generate_json
from app.nova_agent import (
    MisconceptionState,
    NovaState,
    NovaStudentAgent,
    understanding_summary,
)

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SESSIONS_DIR = os.path.join(BASE_DIR, "sessions")

VALID_FORMS = ("pre", "post")
router = APIRouter(tags=["learning-eval"])


class GeneratedTestQuestion(BaseModel):
    """One LLM-generated 4-option MCQ, validated before use."""

    id: str = Field(description="Id of the misconception this question tests.")
    concept: str = Field(default="", description="OOP concept being tested.")
    question: str
    options: List[str] = Field(min_length=4, max_length=4)
    correct_index: int = Field(ge=0, le=3)
    explanation: str = Field(default="", description="Why the correct option is right.")


class GeneratedTestOutput(BaseModel):
    """The full LLM response for one test form."""

    questions: List[GeneratedTestQuestion]


class TestAnswer(BaseModel):
    """One submitted answer."""

    question_id: str
    choice: int


class SubmitTestRequest(BaseModel):
    answers: List[TestAnswer] = Field(default_factory=list)


def _avoid_block(form: str, pre_questions: Optional[List[Dict[str, Any]]]) -> str:
    """Returns prompt text that keeps the post-test questions distinct from the pre-test."""
    if form != "post" or not pre_questions:
        return ""
    lines = []
    for item in pre_questions:
        question = str(item.get("question", "")).strip()
        if question:
            lines.append(f"- {question}")
    if not lines:
        return ""
    return (
        "\nThe PRE-TEST already asked the questions below. Do NOT reuse their wording or "
        "examples in the POST-TEST; write new wording and new examples for the same concepts:\n"
        + "\n".join(lines)
        + "\n"
    )


def _build_test_prompt(
    state: NovaState, form: str, pre_questions: Optional[List[Dict[str, Any]]] = None
) -> str:
    """Builds the single prompt used to generate one test form."""
    misconceptions = json.dumps([
        {
            "id": m.id,
            "concept": m.concept,
            "wrong_belief": m.wrong_concept,
            "correct_concept": m.correct_concept,
            "source_quote": m.source_quote,
            "source_pages": m.source_pages,
        }
        for m in state.misconceptions
    ], indent=2)
    form_note = (
        "This is the PRE-TEST, taken before teaching Nova."
        if form == "pre"
        else "This is the POST-TEST, taken after teaching Nova. Test the same concepts "
        "as the pre-test but with different wording and different examples."
    )
    return f"""
You write a multiple-choice test about Object Oriented Programming for Nova, an AI student.
{form_note}

Write EXACTLY ONE question for EACH misconception listed below, using the id verbatim.
Every question must have EXACTLY 4 options and exactly one correct answer.
Base the correct answer and explanation ONLY on the lecture source quote and the correct
concept. Invent nothing. Exactly one of the three distractors must be Nova's wrong belief
(quote it or lightly paraphrase it); the other distractors must be plausible but wrong.

MISCONCEPTIONS:
{misconceptions}
{_avoid_block(form, pre_questions)}
Return ONLY valid JSON:
{{
  "questions": [
    {{
      "id": "misconception_id_here",
      "concept": "concept here",
      "question": "question here",
      "options": ["option 1", "option 2", "option 3", "option 4"],
      "correct_index": 0,
      "explanation": "why the correct option is right, citing the lecture idea"
    }}
  ]
}}
"""


def _looks_like_wrong_belief(option: str, wrong_belief: str) -> bool:
    """Checks whether an option already expresses the misconception."""
    option_text = option.lower().strip()
    wrong_text = wrong_belief.lower().strip()
    if not option_text or not wrong_text:
        return False
    return wrong_text in option_text or option_text in wrong_text


def _ensure_wrong_belief_distractor(
    question: GeneratedTestQuestion, misconception: MisconceptionState
) -> List[str]:
    """Guarantees that one wrong option is Nova's actual belief."""
    options = list(question.options)
    wrong = (misconception.wrong_concept or "").strip()
    if not wrong:
        return options
    has_wrong = any(
        _looks_like_wrong_belief(option, wrong)
        for index, option in enumerate(options)
        if index != question.correct_index
    )
    if has_wrong:
        return options
    for index in range(len(options)):
        if index != question.correct_index:
            options[index] = wrong
            break
    return options


def generate_test(
    state: NovaState,
    form: str,
    provider: Optional[BaseLLMProvider] = None,
) -> List[Dict[str, Any]]:
    """
    Generates one 4-option MCQ per misconception in a single validated LLM call.

    For the post-test, the pre-test questions are passed as text to avoid, so the
    same concepts are tested with new wording and examples.
    """
    if form not in VALID_FORMS:
        raise ValueError(f"Unknown test form: {form}")
    if not state.misconceptions:
        raise ValueError("This session has no misconceptions to test.")

    pre_questions = None
    if form == "post":
        pre = (state.tests or {}).get("pre") or {}
        pre_questions = pre.get("questions") or []

    result = generate_json(
        _build_test_prompt(state, form, pre_questions),
        GeneratedTestOutput,
        provider=provider,
        retries=1,
    )

    by_id: Dict[str, GeneratedTestQuestion] = {}
    for question in result.questions:
        by_id[question.id] = question

    expected_ids = [m.id for m in state.misconceptions]
    missing = [misconception_id for misconception_id in expected_ids if misconception_id not in by_id]
    if missing:
        raise ValueError(
            "The LLM did not return exactly one question per misconception. "
            f"Missing ids: {missing}"
        )

    questions: List[Dict[str, Any]] = []
    for misconception in state.misconceptions:
        question = by_id[misconception.id]
        if not question.question.strip():
            raise ValueError(f"Empty question generated for misconception {misconception.id}.")
        questions.append({
            "id": misconception.id,
            "concept": question.concept or misconception.concept,
            "question": question.question.strip(),
            "options": _ensure_wrong_belief_distractor(question, misconception),
            "correct_index": question.correct_index,
            "explanation": question.explanation.strip(),
        })
    return questions


def score_test(
    questions: List[Dict[str, Any]], answers: List[Dict[str, Any]]
) -> Dict[str, Any]:
    """
    Scores a test in plain Python.

    Returns per-question results (with the correct option and explanation),
    per-concept percentages, and the overall percentage.
    """
    answer_by_id: Dict[str, Any] = {}
    for answer in answers:
        if isinstance(answer, BaseModel):
            answer = answer.model_dump()
        answer_by_id[str(answer.get("question_id"))] = answer.get("choice")

    per_question: List[Dict[str, Any]] = []
    concept_totals: Dict[str, Dict[str, Any]] = {}
    correct_count = 0

    for question in questions:
        question_id = str(question.get("id"))
        choice = answer_by_id.get(question_id)
        correct_index = int(question.get("correct_index", -1))
        is_correct = choice == correct_index
        if is_correct:
            correct_count += 1

        concept = str(question.get("concept") or "General")
        bucket = concept_totals.setdefault(concept, {"correct": 0, "total": 0})
        bucket["total"] += 1
        if is_correct:
            bucket["correct"] += 1

        per_question.append({
            "question_id": question_id,
            "concept": concept,
            "question": question.get("question", ""),
            "choice": choice,
            "correct_index": correct_index,
            "correct": is_correct,
            "explanation": question.get("explanation", ""),
        })

    total = len(questions)
    per_concept = [
        {
            "concept": concept,
            "correct": bucket["correct"],
            "total": bucket["total"],
            "percentage": round(bucket["correct"] / bucket["total"] * 100.0, 2)
            if bucket["total"]
            else 0.0,
        }
        for concept, bucket in concept_totals.items()
    ]
    overall = round(correct_count / total * 100.0, 2) if total else 0.0

    return {
        "total_questions": total,
        "correct_count": correct_count,
        "overall_percentage": overall,
        "per_question": per_question,
        "per_concept": per_concept,
    }


def _test_percentage(test: Optional[Dict[str, Any]]) -> Optional[float]:
    """Returns a submitted test's overall percentage, or None when it is unfinished."""
    if not test or not test.get("submitted_at"):
        return None
    score = test.get("score")
    value = score.get("overall_percentage") if isinstance(score, dict) else score
    if not isinstance(value, (int, float)):
        return None
    return round(float(value), 2)


def _correct_by_question(test: Optional[Dict[str, Any]]) -> Dict[str, bool]:
    """Maps question id -> correctness for a submitted test."""
    if not test or not test.get("submitted_at"):
        return {}
    score = test.get("score")
    per_question = score.get("per_question") if isinstance(score, dict) else None
    if not isinstance(per_question, list):
        return {}
    return {
        str(row.get("question_id")): bool(row.get("correct"))
        for row in per_question
        if isinstance(row, dict) and row.get("question_id") is not None
    }


def _parse_event_time(value: Any) -> Optional[datetime]:
    """Parses an event timestamp, returning None when it is missing or malformed."""
    if not isinstance(value, str) or not value:
        return None
    try:
        return datetime.fromisoformat(value)
    except ValueError:
        return None


def _teaching_stats(state: NovaState) -> Dict[str, Any]:
    """
    Counts teacher turns and measures the seconds from each teacher_message
    event to the next nova_reply event.
    """
    events = state.events or []
    teacher_turns = 0
    durations: List[float] = []

    for index, event in enumerate(events):
        if event.get("type") != "teacher_message":
            continue
        teacher_turns += 1
        start = _parse_event_time(event.get("time"))
        if start is None:
            continue
        for later in events[index + 1:]:
            if later.get("type") != "nova_reply":
                continue
            end = _parse_event_time(later.get("time"))
            if end is not None and end >= start:
                durations.append((end - start).total_seconds())
            break

    return {
        "teacher_turns": teacher_turns,
        "avg_response_seconds": round(sum(durations) / len(durations), 2)
        if durations
        else None,
        "max_response_seconds": round(max(durations), 2) if durations else None,
    }


def compute_evaluation(state: Any) -> Dict[str, Any]:
    """
    Builds the Stage 9 evaluation for a session in plain Python.

    Scores and gains are None until both tests are submitted. `per_concept`
    combines test correctness with understanding_summary's Nova status/tries.
    """
    if isinstance(state, dict):
        state = NovaState(**state)

    tests = state.tests or {}
    pre_test = tests.get("pre")
    post_test = tests.get("post")
    pre_score = _test_percentage(pre_test)
    post_score = _test_percentage(post_test)

    absolute_gain = None
    normalized_gain = None
    gain_label = None
    if pre_score is not None and post_score is not None:
        absolute_gain = round(post_score - pre_score, 2)
        if pre_score < 100:
            normalized_gain = round((post_score - pre_score) / (100 - pre_score), 3)
            if normalized_gain >= 0.7:
                gain_label = "high"
            elif normalized_gain >= 0.3:
                gain_label = "medium"
            else:
                gain_label = "low"

    summary_rows = understanding_summary(state)["misconceptions"]
    pre_correct = _correct_by_question(pre_test)
    post_correct = _correct_by_question(post_test)

    per_concept = []
    for misconception, row in zip(state.misconceptions, summary_rows):
        per_concept.append({
            "concept": row.get("concept") or misconception.concept,
            "pre_correct": pre_correct.get(misconception.id),
            "post_correct": post_correct.get(misconception.id),
            "status": row.get("status"),
            "tries": row.get("tries", 0),
        })

    corrected = sum(1 for row in summary_rows if row.get("status") == "learned")
    explained = sum(
        1 for row in summary_rows if row.get("status") in ("testing", "learned")
    )

    return {
        "pre_score": pre_score,
        "post_score": post_score,
        "absolute_gain": absolute_gain,
        "normalized_gain": normalized_gain,
        "per_concept": per_concept,
        "misconceptions_corrected": corrected,
        "misconceptions_total": len(state.misconceptions),
        "concepts_explained": explained,
        "teaching_stats": _teaching_stats(state),
        "gain_label": gain_label,
    }


def _check_session_owner(nova: NovaStudentAgent, user: dict) -> None:
    """Raises 403 if the session belongs to a different user. Unowned sessions stay open."""
    if nova.state.owner_id and nova.state.owner_id != str(user["id"]):
        raise HTTPException(status_code=403, detail="You do not own this session.")


def _session_file(session_id: str) -> str:
    """Absolute path of a session JSON file."""
    return os.path.join(SESSIONS_DIR, f"{session_id}.json")


def _load_owned_session(session_id: str, user: dict) -> NovaStudentAgent:
    """Loads a session and checks ownership; raises 404 if it does not exist."""
    path = _session_file(session_id)
    if not os.path.exists(path):
        raise HTTPException(status_code=404, detail="Session not found.")
    nova = NovaStudentAgent.load_state(path)
    _check_session_owner(nova, user)
    return nova


def _validate_form(form: str) -> None:
    """Raises 400 for any form other than pre/post."""
    if form not in VALID_FORMS:
        raise HTTPException(status_code=400, detail="Test form must be 'pre' or 'post'.")


def public_questions(test: Dict[str, Any]) -> List[Dict[str, Any]]:
    """Returns test questions without the answer key or explanation."""
    return [
        {
            "id": question.get("id"),
            "concept": question.get("concept", ""),
            "question": question.get("question", ""),
            "options": question.get("options", []),
        }
        for question in test.get("questions", [])
    ]


def _is_submitted(test: Optional[Dict[str, Any]]) -> bool:
    """True when a test form has a submission timestamp."""
    return bool(test and test.get("submitted_at"))


@router.post("/sessions/{session_id}/tests/{form}")
def get_or_create_test(
    session_id: str, form: str, user: dict = Depends(get_current_user)
) -> Dict[str, Any]:
    """Returns an existing test form or generates it (never exposing answer keys)."""
    _validate_form(form)
    nova = _load_owned_session(session_id, user)
    path = _session_file(session_id)

    test = (nova.state.tests or {}).get(form)
    if test and test.get("questions"):
        return {
            "session_id": session_id,
            "form": form,
            "submitted": _is_submitted(test),
            "questions": public_questions(test),
        }

    try:
        questions = generate_test(nova.state, form, provider=nova.provider)
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to generate test: {str(e)}")

    nova.state.tests[form] = {
        "questions": questions,
        "answers": [],
        "score": None,
        "submitted_at": None,
    }
    nova.save_state(path)
    return {
        "session_id": session_id,
        "form": form,
        "submitted": False,
        "questions": public_questions(nova.state.tests[form]),
    }


@router.post("/sessions/{session_id}/tests/{form}/submit")
def submit_test(
    session_id: str,
    form: str,
    req: SubmitTestRequest,
    user: dict = Depends(get_current_user),
) -> Dict[str, Any]:
    """Scores a submitted test form once, returning per-question feedback."""
    _validate_form(form)
    nova = _load_owned_session(session_id, user)
    path = _session_file(session_id)

    if form == "post" and not _is_submitted((nova.state.tests or {}).get("pre")):
        raise HTTPException(
            status_code=400, detail="Submit the pre-test before the post-test."
        )

    test = (nova.state.tests or {}).get(form)
    if not test or not test.get("questions"):
        raise HTTPException(status_code=404, detail="Test has not been generated yet.")
    if _is_submitted(test):
        raise HTTPException(status_code=409, detail="This test has already been submitted.")

    answers = [answer.model_dump() for answer in req.answers]
    score = score_test(test["questions"], answers)

    test["answers"] = answers
    test["score"] = score
    test["submitted_at"] = datetime.now().isoformat()
    nova._log_event({
        "type": f"{form}test_submitted",
        "score": score["overall_percentage"],
        "correct_count": score["correct_count"],
        "total_questions": score["total_questions"],
    })
    nova.save_state(path)

    return {
        "session_id": session_id,
        "form": form,
        "score": score,
        "results": score["per_question"],
        "submitted_at": test["submitted_at"],
    }


@router.get("/sessions/{session_id}/evaluation")
def get_evaluation(
    session_id: str, user: dict = Depends(get_current_user)
) -> Dict[str, Any]:
    """Returns the Stage 9 learning evaluation for a session."""
    nova = _load_owned_session(session_id, user)
    return compute_evaluation(nova.state)
